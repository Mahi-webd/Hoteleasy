// Builds supabase/functions/assistant/guide.ts from src/help/articles/*.md, so the in-app guides and the
// assistant use the same text. Run: npm run build:help   (prebuild runs it with --check: fails if out of date)
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
// Git on Windows may check files out with CRLF line endings; compare and parse with LF.
const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");
const dir = join(root, "src/help/articles");
const target = join(root, "supabase/functions/assistant/guide.ts");

const articles = readdirSync(dir).filter((f) => f.endsWith(".md")).sort().map((f) => {
  const raw = read(join(dir, f));
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${f}: missing --- header ---`);
  const meta = Object.fromEntries(m[1].split("\n").map((l) => [l.slice(0, l.indexOf(":")).trim(), l.slice(l.indexOf(":") + 1).trim()]));
  if (!meta.title || !meta.screen) throw new Error(`${f}: needs title and screen`);
  return { id: f.replace(/\.md$/, ""), title: meta.title, screen: meta.screen, body: m[2].trim() };
});

// screens the assistant may link to, from the sidebar
const sidebar = read(join(root, "src/components/AppSidebar.tsx"));
const screens = [...sidebar.matchAll(/\{ key: "([^"]+)", label: "([^"]+)"/g)].map((m) => ({ key: m[1], label: m[2] }));
const keys = new Set(screens.map((x) => x.key));
for (const a of articles) if (!keys.has(a.screen)) throw new Error(`${a.id}: screen "${a.screen}" is not in the sidebar`);

const guide = articles.map((a) => `## ${a.title}\n(screen: ${a.screen})\n\n${a.body}`).join("\n\n");
const out = `// GENERATED by scripts/build-help.mjs from src/help/articles. Do not edit by hand.\nexport const GUIDE = ${JSON.stringify(guide)};\nexport const SCREENS: { key: string; label: string }[] = ${JSON.stringify(screens)};\n`;

if (process.argv.includes("--check")) {
  if (!existsSync(target) || read(target) !== out) {
    console.error("supabase/functions/assistant/guide.ts is out of date: run npm run build:help (and redeploy the assistant function)");
    process.exit(1);
  }
  console.log(`Help guide OK: ${articles.length} articles.`);
} else {
  writeFileSync(target, out);
  console.log(`Wrote ${target} (${articles.length} articles, ${guide.length} characters).`);
}
